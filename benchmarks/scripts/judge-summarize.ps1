<#
.SYNOPSIS
  Append the Final Summary section to <RunId>.md after the qualitative
  AI judging pass is complete.

.DESCRIPTION
  Phase 3 of the benchmark workflow. Run AFTER:
    1. bench-run.ps1 -Phase finish    (computes cost/time/tokens)
    2. judge-run.ps1                  (runs R1-R10 + stubs judge.md per tool)
    3. (you paste judge-prompt-<tool>.md into an agent for each tool,
        agent fills in 1-5 quality scores + bug list in <tool>/judge.md)

  Then:
    judge-summarize.ps1 -RunId <id> -JudgeAgent <name>

  Parses each tool's judge.md for 1-5 quality scores and bug count.
  Refuses to run if any tool's scores are incomplete. Computes a
  composite ranking weighted 50% cost, 30% quality avg, 20% bug count.
  Appends a Final Summary block at the bottom of <RunId>.md between
  sentinel markers so re-runs replace cleanly.

.PARAMETER RunId
  RunId directory name.

.PARAMETER Benchmark
  Benchmark folder under benchmarks/. Default: tic-tac-toe.

.PARAMETER JudgeAgent
  Name of the agent/model that did the qualitative judging.
  Recorded in the methodology note. Examples:
    "claude-opus-4-7", "gpt-5 (via opencode)", "codex-cli with gpt-5"

.EXAMPLE
  .\judge-summarize.ps1 -RunId 2026-05-21-0818 -JudgeAgent claude-opus-4-7
#>

[CmdletBinding()]
param(
    [Parameter(Mandatory)]
    [string]$RunId,

    [string]$Benchmark = "tic-tac-toe",

    [Parameter(Mandatory)]
    [string]$JudgeAgent
)

$ErrorActionPreference = "Stop"

# ============================================================
# Config
# ============================================================

$DIMS = @("Readability", "Test breadth", "UX polish", "Defensiveness", "Documentation")

# Composite ranking weights
$W_COST    = 0.50
$W_QUALITY = 0.30
$W_BUGS    = 0.20

# Sentinel markers -- re-running replaces everything between them
$START_MARKER = "<!-- JUDGE-SUMMARY-START (generated by judge-summarize.ps1; do not edit by hand) -->"
$END_MARKER   = "<!-- JUDGE-SUMMARY-END -->"

# ============================================================
# Path resolution
# ============================================================

$repoRoot     = (Resolve-Path (Join-Path $PSScriptRoot "..\..")).Path
$resultsDir   = Join-Path $repoRoot "benchmarks\$Benchmark\results\runs\$RunId"
$mainMdPath   = Join-Path $resultsDir "$RunId.md"
$mainJsonPath = Join-Path $resultsDir "$RunId.json"

if (-not (Test-Path $resultsDir)) {
    throw "Results dir not found: $resultsDir"
}
if (-not (Test-Path $mainMdPath)) {
    throw "Main RunId.md not found: $mainMdPath`n  Run bench-run.ps1 -Phase finish first."
}
if (-not (Test-Path $mainJsonPath)) {
    throw "Main RunId.json not found: $mainJsonPath`n  Run bench-run.ps1 -Phase finish first."
}

# ============================================================
# Helpers
# ============================================================

function Parse-JudgeMd {
    param(
        [Parameter(Mandatory)][string]$Path,
        [Parameter(Mandatory)][string]$ToolName
    )
    $content = Get-Content -Raw -Path $Path

    # Scores -- support both formats agents have actually used:
    #   - Bullet form:   `- Readability: 4`
    #   - Table form:    `| Readability | 4 | ... |`  (column 2 is the score)
    $scores  = @{}
    $missing = @()
    foreach ($d in $DIMS) {
        $escaped = [Regex]::Escape($d)
        $val = $null

        # Table format -- check first since it's what the agent used here
        $tableRe = '(?im)^\|\s*' + $escaped + '\s*\|\s*(\d+)\s*\|'
        $m = [Regex]::Match($content, $tableRe)
        if ($m.Success) {
            $n = [int]$m.Groups[1].Value
            if ($n -ge 1 -and $n -le 5) { $val = $n }
        }

        # Bullet format fallback
        if ($null -eq $val) {
            $bulletRe = '(?im)^[\t ]*-[\t ]*' + $escaped + '\s*:\s*(\d+)'
            $m = [Regex]::Match($content, $bulletRe)
            if ($m.Success) {
                $n = [int]$m.Groups[1].Value
                if ($n -ge 1 -and $n -le 5) { $val = $n }
            }
        }

        if ($null -ne $val) {
            $scores[$d] = $val
        } else {
            $missing += $d
        }
    }

    # Bug count -- locate the "## Bug list" section, then handle both
    # table form (count rows whose first cell is a number) and bullet form
    # (count - lines that aren't placeholders).
    # NOTE: regex patterns MUST be single-quoted -- "$(.*)" would be a
    # PowerShell sub-expression and execute as a command otherwise.
    $bugCount = 0
    $bugSectionRe = '(?ms)^##\s+Bug list\s*\r?\n([\s\S]*?)(?=^##\s|\z)'
    $bugSection = [Regex]::Match($content, $bugSectionRe)
    if ($bugSection.Success) {
        $sectionContent = $bugSection.Groups[1].Value

        # Table form: rows like `| 1 | description | ... |`
        $tableRowMatches = [Regex]::Matches($sectionContent, '(?m)^\|\s*\d+\s*\|')
        if ($tableRowMatches.Count -gt 0) {
            $bugCount = $tableRowMatches.Count
        } else {
            # Bullet form
            $lines = $sectionContent -split "`r?`n"
            foreach ($line in $lines) {
                if ($line -notmatch '^\s*-\s+(.+)$') { continue }
                $bullet = $matches[1].Trim()
                if ($bullet -match '^\(') { continue }                       # `- (none found)`
                if ($bullet -match '^(none|n/?a|tbd|no bugs)\b') { continue }
                if ($bullet -match '^_') { continue }                        # `- _placeholder_`
                $bugCount++
            }
        }
    }

    return [PSCustomObject]@{
        Tool    = $ToolName
        Scores  = $scores
        Missing = $missing
        Bugs    = $bugCount
    }
}

# ============================================================
# Discover tools + parse their judge.md
# ============================================================

$toolDirs = Get-ChildItem -Path $resultsDir -Directory -ErrorAction SilentlyContinue |
    Where-Object { Test-Path (Join-Path $_.FullName "judge.md") }

if (-not $toolDirs -or $toolDirs.Count -eq 0) {
    throw "No tool dirs with judge.md found under $resultsDir`n  Did judge-run.ps1 complete?"
}

Write-Host ""
Write-Host "Judge summarize" -ForegroundColor Cyan
Write-Host "==============="
Write-Host "  RunId:       $RunId"
Write-Host "  Benchmark:   $Benchmark"
Write-Host "  JudgeAgent:  $JudgeAgent"
Write-Host "  Tools:       $(($toolDirs | ForEach-Object Name) -join ', ')"
Write-Host ""

$parsed     = @()
$incomplete = @()
foreach ($td in $toolDirs) {
    $jmp = Join-Path $td.FullName "judge.md"
    $p = Parse-JudgeMd -Path $jmp -ToolName $td.Name
    $parsed += $p
    if ($p.Missing.Count -gt 0) {
        $incomplete += [PSCustomObject]@{
            Tool    = $td.Name
            Missing = $p.Missing
            Path    = $jmp
        }
    }
}

if ($incomplete.Count -gt 0) {
    Write-Host "ERROR: incomplete qualitative scoring." -ForegroundColor Red
    Write-Host ""
    foreach ($i in $incomplete) {
        Write-Host "  $($i.Tool): missing $($i.Missing -join ', ')" -ForegroundColor Yellow
        Write-Host "    $($i.Path)" -ForegroundColor DarkGray
    }
    Write-Host ""
    Write-Host "Open each judge.md and fill in the 1-5 score for every dimension." -ForegroundColor Yellow
    Write-Host "Then re-run this script." -ForegroundColor Yellow
    exit 1
}

# ============================================================
# Pull cost + R1-R10 from the existing artifacts
# ============================================================

$mainJson = Get-Content -Raw -Path $mainJsonPath | ConvertFrom-Json

$costByTool = @{}
foreach ($t in $mainJson.tools) {
    $costByTool[$t.Tool] = [double]$t.Cost
}

$r1r10ByTool = @{}
foreach ($td in $toolDirs) {
    $jjPath = Join-Path $td.FullName "_judge-functional.json"
    if (Test-Path $jjPath) {
        $jj = Get-Content -Raw -Path $jjPath | ConvertFrom-Json
        $pass = 0; $total = 0
        if ($jj.results) {
            foreach ($r in $jj.results.PSObject.Properties) {
                $total++
                if ($r.Value.status -eq 'PASS') { $pass++ }
            }
        }
        $r1r10ByTool[$td.Name] = "$pass / $total"
    } else {
        $r1r10ByTool[$td.Name] = "?"
    }
}

# ============================================================
# Composite ranking
# ============================================================

$minCost = ($costByTool.Values | Measure-Object -Minimum).Minimum
if ($minCost -le 0) { $minCost = 0.0001 }

$ranked = @()
foreach ($p in $parsed) {
    $cost = if ($costByTool.ContainsKey($p.Tool)) { $costByTool[$p.Tool] } else { 0.0 }

    # Higher when cheaper. The cheapest tool gets 1.0; double the cheapest gets 0.5.
    $costScore = if ($cost -gt 0) { $minCost / $cost } else { 1.0 }

    $qualityAvg   = ($p.Scores.Values | Measure-Object -Average).Average
    $qualityScore = $qualityAvg / 5.0

    # Higher when fewer bugs. 0 bugs = 1.0; 1 bug = 0.5; 2 bugs = 0.33...
    $bugScore = 1.0 / (1.0 + $p.Bugs)

    $composite = ($W_COST * $costScore) + ($W_QUALITY * $qualityScore) + ($W_BUGS * $bugScore)

    $ranked += [PSCustomObject]@{
        Tool         = $p.Tool
        Cost         = $cost
        Quality      = $p.Scores
        QualityAvg   = $qualityAvg
        Bugs         = $p.Bugs
        Composite    = $composite
        R1R10        = $r1r10ByTool[$p.Tool]
    }
}

$ranked = $ranked | Sort-Object Composite -Descending

# ============================================================
# Build the summary markdown block
# ============================================================

$lines = @()
$lines += ""
$lines += "---"
$lines += ""
$lines += $START_MARKER
$lines += ""
$lines += "## Final summary"
$lines += ""
$lines += "_Qualitative scoring by ``$JudgeAgent`` on $(Get-Date -Format 'yyyy-MM-dd')._"
$lines += "_Composite weighting: cost 50%, quality avg 30%, bug count 20%. Higher composite = better._"
$lines += ""
$lines += "### Composite ranking"
$lines += ""
$lines += "| Rank | Tool | Cost (USD) | R1-R10 | Quality avg | Bugs found | Composite |"
$lines += "|---:|---|---:|---:|---:|---:|---:|"
$rank = 0
foreach ($r in $ranked) {
    $rank++
    $lines += ('| {0} | {1} | ${2:F4} | {3} | {4:F2} | {5} | {6:F3} |' -f `
        $rank, $r.Tool, $r.Cost, $r.R1R10, $r.QualityAvg, $r.Bugs, $r.Composite)
}
$lines += ""
$lines += "### Quality scores by dimension"
$lines += ""
$header = "| Dimension"
$align  = "|---"
foreach ($r in $ranked) {
    $header += " | $($r.Tool)"
    $align  += " |---:"
}
$header += " |"
$align  += " |"
$lines += $header
$lines += $align
foreach ($d in $DIMS) {
    $row = "| $d"
    foreach ($r in $ranked) {
        $row += " | $($r.Quality[$d])"
    }
    $row += " |"
    $lines += $row
}
$avgRow = "| **Average**"
foreach ($r in $ranked) {
    $avgRow += (" | **{0:F2}**" -f $r.QualityAvg)
}
$avgRow += " |"
$lines += $avgRow
$lines += ""
$lines += "### Bug counts"
$lines += ""
foreach ($r in $ranked) {
    $lines += "- **$($r.Tool)**: $($r.Bugs) bug(s) beyond R1-R10 -- see [judge.md]($($r.Tool)/judge.md) for detail"
}
$lines += ""
$lines += "### Methodology note"
$lines += ""
$lines += "Cost is API-retail-equivalent per ccusage, not what you actually paid (subscription users pay flat; BYOK gateway users pay the underlying provider). Quality scores are subjective and reflect one agent's read of source + screenshots -- a different judge agent will produce different numbers. Bug count only includes bugs the qualitative judge flagged beyond the R1-R10 functional tests."
$lines += ""
$lines += $END_MARKER

$summaryBlock = $lines -join "`n"

# ============================================================
# Append or replace in <RunId>.md
# ============================================================

$mainMd = Get-Content -Raw -Path $mainMdPath
$markerIdx = $mainMd.IndexOf($START_MARKER)
if ($markerIdx -ge 0) {
    # Truncate at the position of the leading "---" that precedes the marker.
    $beforeMarker = $mainMd.Substring(0, $markerIdx)
    $beforeMarker = $beforeMarker.TrimEnd(@("`r", "`n", " ", "`t"))
    # Strip a single trailing "---" separator line that we inserted.
    if ($beforeMarker.EndsWith("---")) {
        $beforeMarker = $beforeMarker.Substring(0, $beforeMarker.Length - 3).TrimEnd(@("`r", "`n", " ", "`t"))
    }
    $mainMd = $beforeMarker + "`n" + $summaryBlock + "`n"
    Write-Host "Replaced existing Final Summary section." -ForegroundColor Cyan
} else {
    $mainMd = $mainMd.TrimEnd() + "`n" + $summaryBlock + "`n"
    Write-Host "Appended Final Summary section." -ForegroundColor Cyan
}

Set-Content -Encoding utf8 -Path $mainMdPath -Value $mainMd

# ============================================================
# Console output
# ============================================================

Write-Host ""
Write-Host "Composite ranking:" -ForegroundColor Green
$rank = 0
foreach ($r in $ranked) {
    $rank++
    Write-Host ("  #{0}  {1,-10}  cost=`${2,-7:F4}  quality={3,-5:F2}  bugs={4,-3}  composite={5:F3}" -f `
        $rank, $r.Tool, $r.Cost, $r.QualityAvg, $r.Bugs, $r.Composite) -ForegroundColor Green
}
Write-Host ""
Write-Host "Updated: $mainMdPath" -ForegroundColor Yellow
Write-Host ""
